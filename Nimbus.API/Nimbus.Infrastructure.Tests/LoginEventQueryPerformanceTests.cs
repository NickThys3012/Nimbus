using Microsoft.Data.SqlClient;
using Microsoft.EntityFrameworkCore;
using Nimbus.Infrastructure.Persistence;
using Nimbus.Infrastructure.Persistence.Repositories;
using Testcontainers.MsSql;
namespace Nimbus.Infrastructure.Tests;

/// <summary>
///     Issue #21: the admin "recent sign-ins" list must stay fast with a large audit table, i.e. it must
///     be served by the <c>OccurredAt</c> index (ordered seek, no sort over the whole table).
/// </summary>
[TestFixture]
public class LoginEventQueryPerformanceTests
{
    private const int Rows = 100_000;
    private MsSqlContainer _sqlServer = null!;

    [OneTimeSetUp]
    public async Task OneTimeSetUpAsync()
    {
        _sqlServer = new MsSqlBuilder("mcr.microsoft.com/mssql/server:2022-latest").Build();
        await _sqlServer.StartAsync();

        await using var db = CreateContext();
        await db.Database.MigrateAsync();
        await db.Database.ExecuteSqlRawAsync($"""
            INSERT INTO LoginEvents (Id, OccurredAt, UserId, Email, Succeeded, MaskedIp, FailureReason)
            SELECT NEWID(), DATEADD(SECOND, -n, SYSUTCDATETIME()), NULL, 'user' + CAST(n % 500 AS nvarchar(10)) + '@example.test',
                   CASE WHEN n % 3 = 0 THEN 0 ELSE 1 END, '10.0.x.x', CASE WHEN n % 3 = 0 THEN 'InvalidPassword' ELSE NULL END
            FROM (SELECT TOP ({Rows}) ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS n
                  FROM sys.all_objects a CROSS JOIN sys.all_objects b) numbers
            """);
    }

    [OneTimeTearDown]
    public async Task OneTimeTearDownAsync()
    {
        await _sqlServer.DisposeAsync();
    }

    private AppDbContext CreateContext()
    {
        return new AppDbContext(new DbContextOptionsBuilder<AppDbContext>().UseSqlServer(_sqlServer.GetConnectionString()).Options);
    }

    [Test]
    public async Task ListRecent_ReturnsNewestFirst_FromAHundredThousandRows()
    {
        await using var db = CreateContext();
        var repo = new LoginEventRepository(db);

        var events = await repo.ListRecentAsync(50);

        Assert.That(await db.LoginEvents.CountAsync(), Is.EqualTo(Rows));
        Assert.That(events, Has.Count.EqualTo(50));
        Assert.That(events, Is.Ordered.Descending.By(nameof(Nimbus.Domain.Entities.LoginEvent.OccurredAt)));
    }

    [Test]
    public async Task ListRecent_QueryPlan_UsesTheTimestampIndex_WithoutSorting()
    {
        await using var db = CreateContext();
        var sql = db.LoginEvents.AsNoTracking().OrderByDescending(e => e.OccurredAt).Take(50).ToQueryString();

        await using var conn = new SqlConnection(_sqlServer.GetConnectionString());
        await conn.OpenAsync();
        await using (var on = new SqlCommand("SET SHOWPLAN_XML ON", conn)) await on.ExecuteNonQueryAsync();
        string plan;
#pragma warning disable CA2100 // SQL is generated by EF from a fixed query, no user input
        await using (var cmd = new SqlCommand(sql, conn)) plan = (string)(await cmd.ExecuteScalarAsync())!;
#pragma warning restore CA2100
        await using (var off = new SqlCommand("SET SHOWPLAN_XML OFF", conn)) await off.ExecuteNonQueryAsync();

        using (Assert.EnterMultipleScope())
        {
            Assert.That(plan, Does.Contain("IX_LoginEvents_OccurredAt"));
            Assert.That(plan, Does.Not.Contain("PhysicalOp=\"Sort\""));
            Assert.That(plan, Does.Not.Contain("Clustered Index Scan"));
        }
    }
}
